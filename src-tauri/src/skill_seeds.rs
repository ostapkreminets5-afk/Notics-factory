pub const LATEST_SEED_VERSION: i64 = 2;

pub fn skills_added_in(version: i64) -> impl Iterator<Item = SkillDraft> {
    SEEDS
        .iter()
        .filter(move |seed| seed.since_version == version)
        .map(|seed| SkillDraft {
            name: seed.name.to_owned(),
            stage: seed.stage,
            title: seed.title.to_owned(),
            summary: seed.summary.to_owned(),
            category: seed.category,
            instructions: seed.instructions.to_owned(),
            enabled: seed.enabled,
        })
}
